import { writeFileSync } from "node:fs";
const CDP_BASE = "http://127.0.0.1:9222";
const APP = "http://localhost:6020";
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const res = await fetch(CDP_BASE + "/json/list");
const page = (await res.json()).find((t) => t.type === "page" && t.webSocketDebuggerUrl && !t.url.startsWith("devtools"));
const ws = new WebSocket(page.webSocketDebuggerUrl);
let id = 0; const pending = new Map();
await new Promise((r) => ws.addEventListener("open", r));
ws.addEventListener("message", (ev) => { const m = JSON.parse(ev.data); if (m.id && pending.has(m.id)) { pending.get(m.id)(m.result); pending.delete(m.id); } });
const send = (method, params = {}) => new Promise((r) => { const i = ++id; pending.set(i, r); ws.send(JSON.stringify({ id: i, method, params })); });
await send("Runtime.enable"); await send("Page.enable");
const ev = async (e) => (await send("Runtime.evaluate", { expression: e, returnByValue: true, awaitPromise: true })).result.value;
await send("Page.navigate", { url: APP + "/asistente" });
await sleep(2500);
console.log("URL      :", await ev("location.pathname"));
console.log("data-conv:", await ev("document.querySelectorAll('[data-conv]').length"));
console.log("aside    :", await ev("document.querySelectorAll('aside').length"));
console.log("botones  :", await ev("[...document.querySelectorAll('button')].map(b=>b.textContent.trim()).filter(Boolean).slice(0,25)"));
console.log("texto    :", (await ev("document.body.innerText")).slice(0, 700));
console.log("localStorage necto.assistant:", (await ev("localStorage.getItem('necto.assistant')"))?.slice(0, 200));
ws.close();

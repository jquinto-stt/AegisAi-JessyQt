/**
 * payment-order — Frontend client for the payment order (payment link) API.
 *
 * Models the PayZen `Charge/CreatePaymentOrder` web service, which generates a
 * payment order (payment link + message) deliverable by URL, email, SMS or
 * WhatsApp. See: https://payzen.io/lat/rest/V4.0/api/payment_order-management.html
 *
 * `createPaymentOrder()` POSTs to the backend microservice (module `api`) at
 * `/api/payment-orders` (proxied by Vite to :8080 in dev). The backend holds the
 * PayZen credentials and runs in mock or live mode (PAYZEN_MODE) — the browser
 * NEVER handles Basic Auth secrets. This client only sees the JSON contract.
 */

// ─── Request type ────────────────────────────────────────────────────────────

/** Delivery channel for the payment order. */
export type PaymentOrderChannelType = "URL" | "MAIL" | "SMS" | "WHATSAPP" | "IVR";

/**
 * Request body sent to the backend (`POST /api/payment-orders`).
 *
 * The frontend sends a flat, simple payload; the backend builds PayZen's
 * `channelOptions`/`customer` structures and adds the credentials. The payment
 * link is created via PayZen's URL channel and delivered by WhatsApp from here
 * (see `buildWhatsAppLink`), so the phone is informational on the order.
 *
 * @remarks `amount` is an integer in the currency's smallest unit
 * (e.g. 30050 = 300.50). `currency` is an ISO 4217 code.
 */
export interface CreatePaymentOrderRequest {
  /** Amount in the smallest currency unit (30050 = 300.50). */
  amount: number;
  /** ISO 4217 currency code (e.g. "USD", "PEN", "CLP", "EUR", "BRL"). */
  currency: string;
  /** Merchant order reference. */
  orderId?: string;
  /** Buyer's WhatsApp/phone number in international format (e.g. "+573026643546"). */
  phoneNumber?: string;
  /** Buyer's display name. */
  customerName?: string;
  /**
   * Delivery channel:
   * - "URL": PayZen returns the link and Necto delivers it (wa.me from the UI).
   * - "WHATSAPP": PayZen delivers the link natively to the buyer's WhatsApp.
   * @default "URL"
   */
  channel?: PaymentOrderChannelType;
  /** Locale for the payment pages, e.g. "es_ES". */
  locale?: string;
}

// ─── Response types ──────────────────────────────────────────────────────────

/** Lifecycle status of a payment order. */
export type PaymentOrderStatus = "RUNNING" | "PAID" | "PARTIALLY_PAID" | "EXPIRED" | "CANCELLED";

/** The `answer` payload returned inside a successful PayZen response. */
export interface PaymentOrder {
  /** Unique payment order reference generated by PayZen. */
  paymentOrderId: string;
  /** The payment link the buyer opens to pay. */
  paymentURL: string;
  status: PaymentOrderStatus;
  amount: number;
  currency: string;
  orderId?: string;
  channelType: PaymentOrderChannelType;
  expirationDate?: string;
  /** Creation timestamp (ISO-8601). */
  creationDate: string;
}

/** PayZen REST envelope: `{ status, answer }`. */
export interface CreatePaymentOrderResponse {
  /** "SUCCESS" or "ERROR". */
  status: "SUCCESS" | "ERROR";
  answer: PaymentOrder;
}

/**
 * A persisted payment order as returned by the listing endpoint.
 *
 * Extends the normalized PaymentOrder with the storage/bookkeeping fields the
 * backend adds when saving it to DynamoDB (buyer metadata + save timestamp).
 */
export interface StoredPaymentOrder extends PaymentOrder {
  /** Buyer phone captured at creation (WhatsApp channel), if any. */
  phoneNumber?: string;
  /** Buyer display name, if provided at creation. */
  customerName?: string;
  /** ISO-8601 timestamp of when the backend saved/updated this record. */
  savedAt: string;
}

/** Envelope returned by `GET /api/payment-orders`. */
interface ListPaymentOrdersResponse {
  status: "SUCCESS" | "ERROR";
  answer: StoredPaymentOrder[];
}

// ─── Backend client ────────────────────────────────────────────────────────

/** Base path of the payment-orders backend endpoint (proxied by Vite to :8080). */
const PAYMENT_ORDERS_URL = "/api/payment-orders";

/** Shape of the error body the backend returns on 4xx/5xx. */
interface ApiError {
  error: string;
  code?: string;
  detail?: string;
}

/**
 * Creates a payment order (payment link) by calling the backend microservice.
 *
 * POSTs the request to `/api/payment-orders`. The backend calls PayZen (or mocks
 * it per PAYZEN_MODE) and returns the created payment order (HTTP 201). The
 * credentials stay on the server — this client only sends/receives JSON.
 *
 * @param request - The payment order parameters (amount, currency, channel, ...)
 * @returns A PayZen-shaped response whose `answer.paymentURL` is the shareable link
 * @throws Error with the backend's message when the request is rejected (4xx/5xx)
 */
export async function createPaymentOrder(
  request: CreatePaymentOrderRequest,
): Promise<CreatePaymentOrderResponse> {
  // 1. POST the request to the backend endpoint
  const res = await fetch(PAYMENT_ORDERS_URL, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(request),
  });

  // 2. On error, surface the backend's message so the UI can show it
  if (!res.ok) {
    const err = (await res.json().catch(() => null)) as ApiError | null;
    throw new Error(err?.error ?? `Error ${res.status} al crear la orden de pago.`);
  }

  // 3. The backend returns the PaymentOrder directly (201). Wrap it in the
  //    PayZen envelope shape the UI already consumes.
  const answer = (await res.json()) as PaymentOrder;
  return { status: "SUCCESS", answer };
}

/**
 * Fetches the current status of a payment order by its id.
 *
 * GETs `/api/payment-orders/:id`. The backend queries PayZen and returns the
 * order with its up-to-date `status` (RUNNING = pendiente, PAID = pagada, ...).
 *
 * @param paymentOrderId - The PayZen payment order id
 * @returns The payment order with its current status
 * @throws Error with the backend's message when the order is not found (404)
 */
export async function getPaymentOrder(paymentOrderId: string): Promise<PaymentOrder> {
  const res = await fetch(`${PAYMENT_ORDERS_URL}/${encodeURIComponent(paymentOrderId)}`);
  if (!res.ok) {
    const err = (await res.json().catch(() => null)) as ApiError | null;
    throw new Error(err?.error ?? `Error ${res.status} al consultar la orden.`);
  }
  return (await res.json()) as PaymentOrder;
}

/**
 * Lists every persisted payment link, newest first.
 *
 * GETs `/api/payment-orders`. The backend reads the saved orders from DynamoDB
 * and refreshes each one's status against PayZen before returning them, so the
 * "active links" view always shows the live state (RUNNING / PAID / EXPIRED …).
 *
 * @returns The stored payment orders with their refreshed status
 * @throws Error with the backend's message when the listing fails (5xx)
 */
export async function listPaymentOrders(): Promise<StoredPaymentOrder[]> {
  const res = await fetch(PAYMENT_ORDERS_URL);
  if (!res.ok) {
    const err = (await res.json().catch(() => null)) as ApiError | null;
    throw new Error(err?.error ?? `Error ${res.status} al listar las órdenes.`);
  }
  const body = (await res.json()) as ListPaymentOrdersResponse;
  return body.answer ?? [];
}

// ─── Helpers ──────────────────────────────────────────────────────────────────

/**
 * Converts a human amount (major units, e.g. "300.50") into PayZen's integer
 * smallest-unit amount (e.g. 30050). Returns NaN when the input is not numeric.
 *
 * @param major - Amount typed by the user in major units (with optional decimals)
 * @returns Integer amount in the smallest currency unit
 */
export function toSmallestUnit(major: string): number {
  const value = Number(major);
  if (Number.isNaN(value)) return NaN;
  return Math.round(value * 100);
}

/**
 * Builds a `wa.me` deep link that opens WhatsApp with a prefilled message
 * containing the payment link, so the merchant can send it to the buyer.
 *
 * @param phoneNumber - Recipient number in international format (may include "+", spaces)
 * @param message - Message body (should include the payment URL)
 * @returns A `https://wa.me/<digits>?text=<encoded>` URL
 */
export function buildWhatsAppLink(phoneNumber: string, message: string): string {
  // wa.me requires digits only (no "+", spaces or dashes)
  const digits = phoneNumber.replace(/\D/g, "");
  return `https://wa.me/${digits}?text=${encodeURIComponent(message)}`;
}
